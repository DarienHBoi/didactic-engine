  return nil
end
function Packs.DungeonsFor(inst, who)
  local out = {}
  for _, r in ipairs(Packs.Dungeons(who)) do if r.inst == inst then out[#out + 1] = r end end
  return out
end

--- the route to start with: the first one for you that you haven't outlevelled
function Packs.Suggest(who)
  local fallback
  for _, r in ipairs(Packs.For(who)) do
    local lo, hi = r.lv and r.lv[1] or 1, r.lv and r.lv[2] or 60
    if who.level < hi and who.level >= lo - 1 then return r end
    if who.level < hi and not fallback then fallback = r end
  end
  return fallback
end
