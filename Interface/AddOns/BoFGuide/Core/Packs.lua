-- Route packs. A pack is plain data built by `forever guide-build`; it arrives either as a bundled addon that loads on
-- demand (BoFGuide_Horde, BoFGuide_Alliance) or as a pasted import string (/bofg import; the paid packs). Both end up
-- here, keyed by pack ID; the higher version wins. Import strings are kept in BoFGuideDB.imports and read again at
-- every login, so a pack imported once is there on every character of the account.
local _, ns = ...

local Packs = { byId = {}, routes = {}, order = {}, dungeonQuests = {} }
ns.Packs = Packs
local FORMAT = 1

local function index(pack)
  for _, r in ipairs(pack.routes or {}) do
    r.pack = pack
    -- the quests a dungeon guide finishes inside (a road without dungeons leaves them out; settings.dungeons): only
    -- after its `enter`. Its "before you go" part finishes outdoor quests too, and those went with them (Nov 9, the
    -- RestedXP study 7: "On my own" dropped 109 road quests, the Barrens' Forgotten Pools and Wetlands' Fire Taboo)
    if r.kd == 'dungeon' then
      local inside = false
      for _, s in ipairs(r.steps or {}) do
        if s.o == 'enter' then inside = true end
        if inside and s.o == 'complete' then
          -- (which dungeon guides finish it: a dungeon switched off in the guide book leaves out its own; FB-053)
          for _, q in ipairs(type(s.id) == 'table' and s.id or { s.id }) do
            Packs.dungeonQuests[q] = Packs.dungeonQuests[q] or {}
            Packs.dungeonQuests[q][r.id] = true
          end
        end
      end
    end
    if not Packs.routes[r.id] or (Packs.routes[r.id].pack.ver or 0) <= (pack.ver or 0) then
      if not Packs.routes[r.id] then table.insert(Packs.order, r.id) end
      Packs.routes[r.id] = r
    end
    -- items the route counts in your bags (collect steps, a profession guide's reagents), recipes it asks about
    r.items, r.spells, r.equips = {}, {}, {}
    for _, s in ipairs(r.steps) do
      if s.o == 'collect' and s.id then r.items[s.id] = true end
      if s.o == 'use' and not s.q and s.id then r.items[s.id] = true end   -- a book to read: still in your bags?
      if s.o == 'equip' and s.id then r.equips[s.id] = true r.items[s.id] = true end   -- (in your bags yet?)
      for _, b in ipairs(type(s.buy) == 'table' and s.buy or {}) do   -- a vendor's buy list
        -- (and whether you wear it: a Fishing Pole bought and put in your hands still counts, Nov 5)
        if type(b) == 'table' and b[1] then r.items[b[1]] = true r.equips[b[1]] = true end
      end
      if s.o == 'craft' then for _, rg in ipairs(s.rg or {}) do r.items[rg[1]] = true end end
      if s.o == 'learn' and type(s.id) == 'number' then r.spells[s.id] = true end
      for _, sp in ipairs(s.sp or {}) do r.spells[sp[2]] = true end   -- a training step's spells
      if s.cash then r.cash = true end   -- a stop that waits for coin: the route counts your money and junk
      if s.fi then r.items[s.fi] = true end   -- a quest started from an item: counted in your bags
    end
  end
end

--- the shape the engine relies on (an import is checked before anything reads it)
local function valid(pack)
  if type(pack) ~= 'table' or pack.fmt ~= FORMAT or type(pack.id) ~= 'string' or type(pack.routes) ~= 'table' then
    return false
  end
  for _, r in ipairs(pack.routes) do
    if type(r) ~= 'table' or type(r.id) ~= 'string' or type(r.steps) ~= 'table' then return false end
    for _, s in ipairs(r.steps) do
      if type(s) ~= 'table' or type(s.o) ~= 'string' or type(s.k) ~= 'string' then return false end
    end
  end
  pack.pts, pack.notes, pack.quests, pack.npcs = pack.pts or {}, pack.notes or {}, pack.quests or {}, pack.npcs or {}
  return true
end

--- called by every pack file: BoFGuide_RegisterPack({ fmt = 1, id = ..., routes = {...} })
-- the guide in the client's language: a BoFGuide_<locale> addon (generated by `forever guide-i18n`) hands over the
-- route lines and names in that language; each pack takes them once, as it registers or when they arrive
-- Two languages can meet (owner, Oct 16): the names the game also shows (people, objects, items, flight points,
-- bosses, quest titles and text) follow the CLIENT's language, so they match the game and /targetexact finds them;
-- the guide's own lines follow the language the player CHOSE. Lang.Apply says which file gives which (Packs.Want).
local loc
local want = {}
function Packs.Want(names, lines) want.names, want.lines = names, lines end
function Packs.Wanted() return want.names, want.lines end

local function localize(pack)
  if not loc then return end
  local key = (loc.locale or '') .. '/' .. (loc.namesLocale or '')
  if pack.localized == key then return end
  local T = loc.lines or {}
  local function tr(s) return s and T[s] or s end
  -- (a name the lines' memory holds: only when the names are in the lines' language too)
  local function trName(s) return loc.namesLocale == loc.locale and tr(s) or s end
  pack.title = tr(pack.title)
  for _, n in ipairs(pack.notes or {}) do n.t = tr(n.t) end
  for _, w in ipairs(pack.travel and pack.travel.ways or {}) do w.say = tr(w.say) end   -- (travel.yaml's ways)
  -- the names, always from the pack's own English ones (kept the first time), so a second language file arriving
  -- later can't stack on the first; and English -> this language, for the loop stops' objective names below
  local function copy(t) local c = {} for k, v in pairs(t or {}) do c[k] = v end return c end
  pack.en = pack.en or { npcs = copy(pack.npcs), objs = copy(pack.objs), items = copy(pack.items) }
  local named = {}
  for id, name in pairs(pack.en.npcs) do pack.npcs[id] = (loc.npcs and loc.npcs[id]) or trName(name) named[name] = pack.npcs[id] end
  for id, name in pairs(pack.en.objs) do pack.objs[id] = (loc.objs and loc.objs[id]) or trName(name) named[name] = pack.objs[id] end
  for id, name in pairs(pack.en.items) do pack.items[id] = (loc.items and loc.items[id]) or name named[name] = pack.items[id] end
  -- a quest before it's in your log: its title in the client's language (it must match the quest log and the game's
  -- windows), its objective and story in the language the player reads the guide in (the owner, Oct 16: the German
  -- guide on an English client showed "Tötet Ursal den Raufer..." and should keep doing so). From the English kept
  -- the first time, so a second language file can't stack on the first
  pack.en.quests = pack.en.quests or {}
  for id, q in pairs(pack.quests or {}) do
    if type(q) == 'table' then
      local e = pack.en.quests[id] or { t = q.t, ot = q.ot, st = q.st }
      pack.en.quests[id] = e
      local inClient, read = loc.quests and loc.quests[id], loc.questText and loc.questText[id]
      q.t = inClient and inClient.t or e.t
      q.ot, q.st = read and read.ot or e.ot, read and read.st or e.st
    end
  end
  for _, r in ipairs(pack.routes or {}) do
    r.title = tr(r.title)
    for _, s in ipairs(r.steps or {}) do
      if s.name then
        local node = (s.o == 'fly' or s.o == 'fp') and type(s.id) == 'number' and loc.nodes and loc.nodes[s.id]
        s.name = node or tr(s.name)
      end
      s.desc, s.an = tr(s.desc), tr(s.an)
      s.sy = tr(s.sy)   -- a goto's own words, the card's title (Oct 17: they stayed English)
      -- a loop's stops skip objectives already done by matching the quest log's names: the client's names
      if s.lon then
        s.lonEn = s.lonEn or s.lon
        local t = {}
        for i, n in ipairs(s.lonEn) do t[i] = named[n] or n end
        s.lon = t
      end
    end
  end
  pack.localized = key
  Packs.namesRev = (Packs.namesRev or 0) + 1
end

function BoFGuide_Localize(t)
  if type(t) ~= 'table' then return end
  -- (nothing said which file gives what, an older caller: this file gives both)
  local any = want.names == nil and want.lines == nil
  loc = loc or {}
  if any or t.locale == want.lines then loc.lines, loc.locale, loc.questText = t.lines, t.locale, t.quests end
  if any or t.locale == want.names then
    loc.npcs, loc.objs, loc.items, loc.nodes, loc.bosses, loc.quests = t.npcs, t.objs, t.items, t.nodes, t.bosses, t.quests
    loc.namesLocale = t.locale
  end
  for _, p in pairs(Packs.byId) do localize(p) end
  if ns.MarkDirty then ns.MarkDirty('packs') end
end

--- the lines and names only a paid pack uses, from its locked language file (Core/Paid.lua), added to what the language's
--- own file gave. Before that pack registers: it takes its words then
function Packs.AddLocalized(t)
  if not loc or type(t) ~= 'table' then return end
  local function add(into, from)
    if into then for k, v in pairs(from or {}) do into[k] = v end end
  end
  if t.locale == loc.locale then add(loc.lines, t.lines) add(loc.questText, t.quests) end
  if t.locale == loc.namesLocale then
    add(loc.npcs, t.npcs) add(loc.objs, t.objs) add(loc.items, t.items) add(loc.quests, t.quests)
  end
end

function Packs.Locale() return loc and loc.locale end

--- a line of ours in the language the player reads the guide in (the language file's lines), else as it is: for what
--- isn't in a pack, like the talent plans' names and abouts (Core/Talents.lua)
function Packs.Line(s) return s and loc and loc.lines and loc.lines[s] or s end

function BoFGuide_RegisterPack(pack)
  if not valid(pack) then
    ns.say(ns.L.packFormat)
    return false
  end
  local old = Packs.byId[pack.id]
  if old and (old.ver or 0) > (pack.ver or 0) then return false end
  pack.source = pack.source or 'bundled'
  localize(pack)
  Packs.byId[pack.id] = pack
  Packs.namesRev = (Packs.namesRev or 0) + 1   -- (Text.KnownCreature reads the packs' names again)
  index(pack)
  Packs.taken = nil   -- (the quests the roads take: read again, Packs.ZoneQuests)
  if ns.MarkDirty then ns.MarkDirty('packs') end
  return true
end

--- the quests offered on a map that no road of yours takes (FB-053, Nov 12: "explore each zone fully"): each
--- { x, y, q, npc, lo, lvl, pack } from the packs' zq lists, less any quest a loaded route takes
function Packs.ZoneQuests(map)
  if not Packs.taken then
    local t = {}
    for _, r in pairs(Packs.routes) do
      for _, s in ipairs(r.steps or {}) do
        if s.o == 'accept' or s.o == 'turnin' or s.o == 'complete' then
          for _, q in ipairs(type(s.id) == 'table' and s.id or { s.id }) do t[q] = true end
        end
      end
    end
    Packs.taken = t
  end
  local out, seen = {}, {}
  for _, pack in pairs(Packs.byId) do
    for _, d in ipairs(pack.zq and pack.zq[map] or {}) do
      local q = d[3]
      if not seen[q] and not Packs.taken[q] then
        seen[q] = true
        out[#out + 1] = { x = d[1], y = d[2], q = q, npc = d[4], lo = d[5], lvl = d[6], pack = pack }
      end
    end
  end
  return out
end

-- the guide's data in its own folder (owner, Oct 16: one BoFGuide folder): each file under Data/ hands its content
-- over as a function (BoFGuide_Defer) and nothing is built yet; at login only your faction's routes and your
-- language's lines run, and the rest are let go (DropDeferred), so the game frees them
local deferred = {}
function BoFGuide_Defer(name, fn)
  if type(name) == 'string' and type(fn) == 'function' then deferred[name] = fn end
end
function Packs.HasDeferred(name) return deferred[name] ~= nil end
--- run one of them once (true when it was there)
function Packs.RunDeferred(name)
  local fn = deferred[name]
  if not fn then return false end
  deferred[name] = nil
  return (ns.safecall('data ' .. name, fn))
end
function Packs.DropDeferred() for k in pairs(deferred) do deferred[k] = nil end end
--- run one and hand back what it returns (a locked paid pack's text: Core/Paid.lua), once
function Packs.TakeDeferred(name)
  local fn = deferred[name]
  if not fn then return nil end
  deferred[name] = nil
  local ok, out = ns.safecall('data ' .. name, fn)
  return ok and out or nil
end

--- the bundled pack for a faction (its Data/ file, or an older separate pack addon)
function Packs.LoadFor(faction)
  if not faction then return false end
  local cap = faction:sub(1, 1):upper() .. faction:sub(2)
  if not BoFGuide_UsePackAddons and Packs.RunDeferred('Routes_' .. cap) then return true end
  local name = 'BoFGuide_' .. cap
  if C_AddOns and C_AddOns.IsAddOnLoaded and C_AddOns.IsAddOnLoaded(name) then return true end
  local loader = (C_AddOns and C_AddOns.LoadAddOn) or LoadAddOn
  if not loader then return false end
  local ok, loaded = pcall(loader, name)
  return ok and loaded and true or false
end

--- this account's BattleTag, or nil while the game hides it
function Packs.BattleTag()
  if not BNGetInfo then return nil end
  local _, tag = BNGetInfo()
  tag = ns.clean(tag)
  return type(tag) == 'string' and tag ~= '' and tag or nil
end

--- a pasted import string: unlocked with this account's BattleTag, checked, registered and kept for the next login.
--- Returns the pack, or nil and why (notpack | version | notag | account | damaged | format | older).
function Packs.Import(text)
  local t0 = debugprofilestop and debugprofilestop()
  local pack, why = ns.Codec.Decode(text, Packs.BattleTag())
  if not pack then return nil, why end
  if t0 then   -- how long the decode took on this PC, for /bofg selftest
    ns.db.importMs = ns.db.importMs or {}
    ns.db.importMs[pack.id] = math.floor(debugprofilestop() - t0 + 0.5)
  end
  if type(pack) ~= 'table' or pack.fmt ~= FORMAT then return nil, 'format' end
  if not valid(pack) then return nil, 'damaged' end
  pack.source = 'import'
  if not BoFGuide_RegisterPack(pack) then return nil, 'older' end
  ns.db.imports[pack.id] = (text:gsub('%s+', ''))
  return pack
end

--- the import strings kept from earlier sessions; the ones the game won't unlock yet (BattleTag hidden) are retried
--- by the engine a little later. Returns how many are still waiting.
function Packs.LoadImports()
  local waiting = 0
  for id, text in pairs(ns.db.imports or {}) do
    if not (Packs.byId[id] and Packs.byId[id].source == 'import') then
      local pack, why = Packs.Import(text)
      if not pack then
        if why == 'notag' then waiting = waiting + 1
        elseif why ~= 'older' then ns.say(ns.L.importLost:format(id, ns.L['import_' .. why] or why)) end
      end
    end
  end
  return waiting
end

--- forget a kept import (the routes stay until the next /reload)
function Packs.Forget(id)
  if not (ns.db.imports and ns.db.imports[id]) then return false end
  ns.db.imports[id] = nil
  return true
end

