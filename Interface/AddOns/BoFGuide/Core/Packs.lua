--- leveling routes for this character, in pack order
function Packs.For(who)
  local out = {}
  for _, id in ipairs(Packs.order) do
    local r = Packs.routes[id]
    if not r.kd and r.faction == who.faction and ns.Evaluator.routeApplies(r, who) then out[#out + 1] = r end
  end
  return out
end

--- the other free starts of your faction, each with its legs in order (`nx`): { { head = route, legs = {...} } }.
--- Anyone may follow any road of their side (FB-030, Oct 18: a Dwarf who walked to Goldshire to level with friends found
--- only the Dwarf's road in the menu); the race's own steps there simply don't apply
function Packs.OtherStarts(who)
  local mine, isNext, out = {}, {}, {}
  for _, r in ipairs(Packs.For(who)) do mine[r.id] = true end
  for _, id in ipairs(Packs.order) do local r = Packs.routes[id] if r.nx then isNext[r.nx] = true end end
  for _, id in ipairs(Packs.order) do
    local r = Packs.routes[id]
    if not r.kd and r.faction == who.faction and not mine[id] and not isNext[id] and r.rc
       and not (r.pack and r.pack.tier == 'paid') and ns.Evaluator.routeApplies({ cls = r.cls }, who)
       and not (ns.Travel and not ns.Travel.Reachable(r)) then   -- (Zephras Isle: nothing sails there)
      local legs, seen, x = {}, {}, r
      while x and not seen[x.id] and not x.kd do
        legs[#legs + 1], seen[x.id] = x, true
        x = x.nx and Packs.routes[x.nx]
      end
      -- (when your class first meets a trainer on that road: a Human Mage on the Night Elf road not till the Wetlands
      -- at 20, where Teldrassil has none; `tlv` from the build)
      local first
      for _, l in ipairs(legs) do
        local at = l.tlv and l.tlv[who.class]
        if at and (not first or at < first) then first = at end
      end
      local from = r.lv and r.lv[1] or 1
      out[#out + 1] = { head = r, legs = legs, noTrainer = first == nil,
                        trainsAt = first and first > from + 4 and first or nil }
    end
  end
  return out
end

--- where a road begins, when that's on another continent than you (a Night Elf picking the Human road): its zone's
--- name, else nil
function Packs.StartsAway(r)
  local pts = r and r.pack and r.pack.pts
  if not pts or not ns.Geo then return nil end
  for _, s in ipairs(r.steps or {}) do
    local p = s.p and pts[s.p]
    if p then
      local there = ns.Geo.World(p[1], p[2], p[3])
      local map = ns.clean(C_Map.GetBestMapForUnit and C_Map.GetBestMapForUnit('player'))
      local ok, pos = pcall(C_Map.GetPlayerMapPosition, map, 'player')
      local x, y = ok and pos and ns.clean(pos.x), ok and pos and ns.clean(pos.y)
      local here = map and x and y and ns.Geo.World(map, x * 100, y * 100)
      if there and here and there ~= here then return ns.Text.Map(p[1]) end
      return nil
    end
  end
  return nil
end

--- dungeon guides for this character, in pack order (lowest level first)
function Packs.Dungeons(who)
  local out = {}
  for _, id in ipairs(Packs.order) do
    local r = Packs.routes[id]
    if r.kd == 'dungeon' and r.faction == who.faction and ns.Evaluator.routeApplies(r, who) then out[#out + 1] = r end
  end
  -- lowest level first, free and paid together (the paid ones came in pack order; the QA pass, Oct 20)
  local pos = {}
  for i, r in ipairs(out) do pos[r] = i end
  table.sort(out, function(a, b)
    local la, lb = a.lv and a.lv[1] or 0, b.lv and b.lv[1] or 0
    if la ~= lb then return la < lb end
    return pos[a] < pos[b]
  end)
  return out
end

--- profession guides for this character (they're for both factions), in pack order
function Packs.Professions(who)
  local out = {}
  for _, id in ipairs(Packs.order) do
    local r = Packs.routes[id]
    if r.kd == 'profession' and (r.faction == 'both' or r.faction == who.faction) then out[#out + 1] = r end
  end
  return out
end

--- the Legacy guide for this character's faction (kind legacy), or nil
function Packs.Legacy(who)
  for _, id in ipairs(Packs.order) do
    local r = Packs.routes[id]
    if r.kd == 'legacy' and r.faction == who.faction then return r end
  end
  return nil
end

